// src/tools/efftask/strictness.ts
import type { Caps, PhaseName } from './types.js'

/**
 * 严格度档位 —— 一次 run 里「多好才算够」的那把尺子。
 *
 * ## 它治的是什么
 *
 * 用户的原话:「分析、质疑讨论,以及执行、测试验证、验收老是运行好几轮,这个是什么原因
 * 导致的,是要求太高了吗?」病因不是要求太高,是**没有任何地方声明要求多高**:
 * `acceptPrompt` 手上只有验收点 + 执行状态,一句「什么算通过」都没有,于是每个裁决席位
 * 各按自己的默认人格打分,而 `synthesizeVerdicts` 的缺省合成规则是**全票 AND** ——
 * 每席独立 80% 通过率时 9 席全票通过的概率是 0.8^9 ≈ 13%(见 `Caps.quorum` 的注释)。
 *
 * ## 为什么是「替换」而不是「追加」
 *
 * 第一版设计想把档位文本从 `seatPreamble()` 一个口子注进去。三份独立评审各自指出这条
 * 路走不通,理由是同一个**位置**问题:`seatPreamble` 的产物是 `brief`,而 `brief` 是
 * 提示词的**第一段**(`pipeline.ts` 里 reviewPrompt/verifyPrompt/... 全是 `brief + …`),
 * 写死的判据在**最后一段**、紧挨输出 schema。于是:
 *
 *  - `verifyPrompt` 写死「没有可跑的验证手段,如实说明并**判不通过**」,而初级/中级档要说
 *    的是同一个谓词的反面。P 和 ¬P 出现在同一份提示词里,而 ¬P 在后。
 *  - `reviewPrompt` 写死的三条判据本身就是中级档的内容,还带着「blocking 等同于否决」
 *    和「第 N 轮不过整个任务中止」两句专门调过的放行压力 —— 专家档的一段抬头压不过它们。
 *
 * 结论:**判据本体按档取值**(`reviewRubric` / `verifyRequirement` 直接替换那几行),
 * `seatPreamble` 只承载抬头声明与地板段。注入点是两个,不是一个。
 *
 * ## 缺省 = 现状,逐字节相同
 *
 * `caps.strictness === undefined` 时,本文件的每一个函数都返回**与引入本特性之前逐字
 * 相同**的字符串(判据类)或空串(声明类)。这不是保守,是可验证的承诺:老 run.md 没有
 * 这个字段,而给它一个具名默认档会让一个原本全票跑的旧 run 在 `--resume` 之后**变松**。
 */
export const STRICTNESS_LEVELS = ['初级', '中级', '高级', '专家'] as const
export type Strictness = (typeof STRICTNESS_LEVELS)[number]

export function isStrictness(v: unknown): v is Strictness {
  return typeof v === 'string' && (STRICTNESS_LEVELS as readonly string[]).includes(v)
}

/**
 * 档位派生的圆桌通过比例。
 *
 * **刻意不含 maxIterations。** 第一版把它也编进档位(专家 3→5),评审查出 `maxIterations`
 * 是一个**双关**旋钮:`pipeline.ts` 的 `roundtableWithInfraRetry` 拿同一个数当「infra
 * 失败席位最多重派几桌」。抬高它意味着上游 429 时每一场圆桌多烧两轮调用,而这和「多好
 * 才算够」没有任何关系。严格度的本质是判据,不是数字。
 *
 * 数值在小席位下会退化,这是整数比例判据(`approving * 100 >= need * judged`)的算术
 * 事实,不是缺陷 —— 但**必须在关口上说出来**(见 `quorumSeatsNeeded`):
 *   51 在 1~2 席 = 全票;80 在 1~4 席 = 全票。
 * 关口印百分比会骗人,要印这一关实际席位数下的绝对门槛。
 */
export const STRICTNESS_QUORUM: Record<Strictness, number> = {
  初级: 34, 中级: 51, 高级: 80, 专家: 100,
}
/**
 * 初级和中级**必须是两个数**,而第一版让它们都等于 51。
 *
 * 两位评审员和一位验收员各自独立指出同一件事:两档在数值上逐字节相同,判据文本又几乎
 * 只差措辞(「照这个方案干下去必然跑不起来」vs「会让执行失败」),于是用户按一下 `>`
 * 从初级收紧一档,**什么都不会发生**。一个按了没反应的旋钮比没有更糟。
 *
 * 34/51/80/100 在**每一个** ≥2 的席位数上都严格单调(1 席时四档必然相同,那是算术):
 *
 *      席位   2    3    4    5    6
 *      初级   1    2    2    2    3
 *      中级   2    2    3    3    4
 *      高级   2    3    4    4    5
 *      专家   2    3    4    5    6
 *
 * 34 ≈「三分之一」,读得出意思。它在 2 席下确实允许**一席放行**,而那正是初级档
 * (「demo 而已」)想要的形态 —— 地板仍然管着「到底做没做」,而关口印的是绝对席位数
 * (「圆桌 验收 1/2 席赞成即通过」),用户按下确认之前看得见这件事。
 */

/**
 * 本档位下这一关**实际**需要几席赞成 —— 关口和详情页印的就是这个数,不是百分比。
 *
 * 与 `synthesizeVerdicts` 的判据(`approving * 100 >= need * judged.length`)同构:
 * 那边是整数乘法比较,这边求满足它的最小整数。两处各写一份浮点近似的话,关口印 2
 * 而圆桌要 3 —— 而用户只会在节点被打回时才发现。
 */
export function quorumSeatsNeeded(quorum: number, seats: number): number {
  if (seats <= 0) return 0
  for (let a = 1; a <= seats; a++) if (a * 100 >= quorum * seats) return a
  return seats
}

/**
 * 这一关的圆桌门槛最终取哪个值。
 *
 * **用户显式写过 quorum 或 quorumSeats 时,档位的数值维度整个不参与。** 理由是
 * `synthesizeVerdicts` 里的 `seatsOnly` 分支:一个只写了 `quorumSeats=2` 的用户,今天
 * 比例维度是**不设限**的(「至少 2 人通过」的意思是把门槛换成 2 席,不是「2 席并且
 * 全票」)。档位一旦给 quorum 填上任何值,`seatsOnly` 当场变 false、比例维度重新生效 ——
 * 5 席下用户选了最松的初级档,门槛反而从 2 席涨到 3 席。**选了最松的档反而变严**是这个
 * 旋钮最不能有的失败形态。
 */
export function resolvedQuorum(caps: Caps): number | undefined {
  if (caps.quorum !== undefined || caps.quorumSeats !== undefined) return caps.quorum
  return caps.strictness === undefined ? undefined : STRICTNESS_QUORUM[caps.strictness]
}

/**
 * 档位判据真正生效的四个环节。
 *
 * **刻意不等于 `pipeline.ts` 的 `JUDGING_PHASES`** —— 那个集合有五个成员,多一个
 * `observer`。观察评分的输出是 `{plan:{score,rationale}, exec:{…}}`,**根本没有 blocking
 * 字段**,给它一段讲「什么该进 blocking」的判据最好的结果是白付 token,最坏的结果是评分
 * 口径被带偏 —— 而 `caps.scoreThreshold` 一旦设了,低分会换来一轮真实的返工。
 */
export const STRICTNESS_JUDGING: ReadonlySet<PhaseName> = new Set<PhaseName>([
  'review', 'verify', 'accept', 'integrate',
])

/**
 * 质疑讨论的判据本体 —— **替换** `reviewPrompt` 里写死的那几行。
 *
 * 缺省档返回的字符串与引入本特性之前**逐字相同**,包括 `round > 1` 那个分支。
 *
 * 中级 = 现状那三条,一字不改。这让「中级」名副其实地等于今天的判据,于是四档里只有
 * 三档需要用户重新建立直觉。
 */
export function reviewRubric(s: Strictness | undefined, round: number): string {
  const repeat = repeatRule(s, round)
  if (s === undefined) return DEFAULT_REVIEW_RUBRIC + repeat
  return `判据(本次严格度:${s}):\n` + REVIEW_RUBRIC[s] + repeat
}

const DEFAULT_REVIEW_RUBRIC =
  `判据:\n` +
  `- blocking 只填**会让执行失败、或让产出没法验收**的问题。\n` +
  `- 方案不需要完美,只需要「能开始干、干完能按验收点验」。能达到这条就判通过。\n` +
  `- 可以更好但不阻塞的,写进 comments,**不要**放进 blocking(放进去等同于否决)。\n`

