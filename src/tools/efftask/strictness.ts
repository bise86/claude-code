/**
 * 与档位**无关**的地板。
 *
 * 为什么需要它:评审推演出一条完整的路径。降到初级后,verify 关「无可跑验证手段不判不
 * 通过」+ accept 关「验收点里没写的不要求」+ quorum 51 在 3 席下变成 2/3,一个执行者写
 * 三行自述、`git status` 全空的节点可以一路 ACCEPTED。
 *
 * **诚实地说清它是什么:这是提示词层的缓解,不是那条路的修复。** 模型可以无视它。代码层
 * 今天挡不住零改动的执行叶子,而且这一点在引入档位**之前就成立**:空产出闸门只检查
 * `execStatus === ''`;`verifySnapshot` 只用来作废一轮**改动了工作区**的验证,对「什么都
 * 没改」完全沉默;`worktreePool` 对零改动返回 `{ok:true, merged:false}`。全仓库没有任何
 * 一处要求一个执行叶子的分支相对集成分支有非空 diff —— 那道结构性闸门还不存在,它有自己
 * 的设计面(非隔离运行没有 diff 可取、纯文档/纯决策节点会误伤),不该顺手挂在这个旋钮上。
 * 初级档改变的是**概率**不是**可达性**。
 *
 * 最后那一句(「降档降的是多好才算够」)是整段的关键 —— 它给模型一个**解释降档文本的
 * 框架**,而不是一条额外规则。没有它,「初级」这个词本身就是可以自由外推的邀请函。
 *
 * **只在设了档位时出现**,否则就破坏了「不设档 = 逐字节相同」那条承诺。不设档时全票 +
 * 空判据本来就是最严的形态,这段地板对它没有任何边际作用。
 */
const FLOOR =
  `无论本次严格度是哪一档,下面三条都不放行:\n` +
  `1. 执行者没有报告任何产出,或报告的内容与目标无关;\n` +
  `2. 报告里声称做了某件事,而你在产出/文件/命令输出里找不到它做过的任何痕迹;\n` +
  `3. 你自己没有看过任何产出(代码、diff、命令输出)就要判通过。\n` +
  `遇到其中任意一条,pass 一律为 false,并在 blocking 里写明是哪一条。\n` +
  `**降档降的是「多好才算够」,不降「到底做没做」。**\n`

/**
 * 质疑讨论那一关**自己的**地板 —— 和上面那份是两码事,而这是拿一条 P0 换来的。
 *
 * 上面那份讲的是「产出」:没报告任何产出 / 找不到做过的痕迹 / 没看过任何产出就放行。
 * 而 review 判的是**方案**,那时**一行代码都还没写** —— 同一份提示词下面就写着「一行
 * 代码都不会写」。于是第 1 条和第 3 条在评审时**恒真**,而结论是「pass 一律为 false」。
 *
 * 后果的方向正好和这个特性的目的相反:**只要设了任何一档,评审就比不设档更难过**,
 * 而用户去降档恰恰是为了少跑几轮。验收员把提示词打出来才看见 —— 判据在最后一段
 * 「能达到这条就判通过」,地板在第一段「一律为 false」,是这份设计自己用来否决
 * 「追加注入」方案的那个论据(P 和 ¬P 同在,¬P 在后)在地板上重犯了一遍。
 */
const REVIEW_FLOOR =
  `无论本次严格度是哪一档,下面三条都不放行:\n` +
  `1. 方案是空的、或与目标无关;\n` +
  `2. 方案声称的做法,你在它给出的落点(文件/函数/命令)上找不到对应的东西;\n` +
  `3. 你自己没有真的读过这份方案就要判通过。\n` +
  `遇到其中任意一条,pass 一律为 false,并在 blocking 里写明是哪一条。\n` +
  `**降档降的是「方案要写多细」,不降「到底有没有方案」。**\n`

/**
 * 每一关在核心判据之外还要补的那一句。
 *
 * review 和 verify 不在这里 —— 它们的判据是**整段替换**的(`reviewRubric` /
 * `verifyRequirement`),再补一句就成了同一件事说两遍。
 */
const PHASE_EXTRA: Partial<Record<PhaseName, Record<Strictness, string>>> = {
  accept: {
    初级: `- 对照验收点逐条判,达成即通过;验收点里没写的不要求。\n`,
    /**
     * 中级这一条改写过一次。原来写的是「执行者自述与实际产出对不上时不通过」——
     * 而 `FLOOR` 第 2 条逐字是同一个意思,两句话会同时出现在同一份提示词里。删掉重复
     * 之后中级和初级在这一关**完全相同**,那反过来正是「两档实质等价」的证据。
     *
     * 现在这条挂在执行侧的**留痕**上(见 `EXEC_SIDE`:中级要求把未做项单起一行写成
     * 「本轮未做:…」)。两边扣在一起才构成一个可检验的差别:初级不问没做的那些,
     * 中级要逐条核对它们是不是验收点要的。
     */
    中级: `- 对照验收点逐条判;执行者在 execStatus 里列出的「本轮未做」各项,\n` +
      `  逐条核对是否属于验收点的要求 —— 属于的,不通过。\n`,
    高级: `- 对照验收点逐条判;验收点本身有遗漏时可以指出,但只在「遗漏会让目标落空」时\n` +
      `  进 blocking。\n`,
    专家: `- 按**目标**判,不只按验收点判:验收点全达成而目标没达成的,不通过。\n`,
  },
  integrate: {
    初级: `- 子任务合起来覆盖了父目标的主路径即通过。\n`,
    /**
     * 和 accept 的中级同一处手术:原来那半句「产出与它自己的验收点对不上时不通过」
     * 逐字是 `FLOOR` 第 2 条,两句会同时出现在一份提示词里,而删掉之后这一档就和初级
     * 完全相同了。改成挂在执行侧的**留痕**上,才是一个可检验的差别。
     */
    中级: `- 子任务合起来覆盖了父目标的主路径即通过;但子任务在 execStatus 里标为\n` +
      `  「本轮未做」的各项,凡是落在**父目标验收点**上的,不通过。\n`,
    高级: `- 除主路径外,子任务之间的接缝(谁调谁、数据怎么流)要能说清,说不清的指出\n` +
      `  是哪一处。\n`,
    专家: `- 还要判「合起来是否引入了单看任何一个子任务都看不出来的问题」。\n`,
  },
}

/**
 * **分析**环节收到的那一段 —— 和执行侧是两份,而这是拿一条 P1 换来的。
 *
 * 原来两个环节共用 `EXEC_SIDE`,于是分析席位收到的是:「先把主路径做通」(它不写代码)、
 * 「方案的验收点与 keyPoints 里点名的事项一件都不能少」(循环 —— 验收点正是它这一次要
 * 写的东西)、「不做的写进 execStatus」(**它的输出 schema 里根本没有这个字段**)。三句
 * 全部落空,而同一份文本还会经 fuse 和精化再进第二、第三份分析提示词。
 *
 * 分析侧真正该被档位调节的是**验收点定到多高** —— 那是这一关唯一的产物,也是后面四关
 * 全部判据的锚。
 */
const PLAN_SIDE: Record<Strictness, string> = {
  初级:
    `本次严格度:**初级** —— 方案覆盖主路径即可。\n` +
    `验收点写成「跑什么命令、看到什么结果」就够,不必覆盖边界与错误路径。\n`,
  中级:
    `本次严格度:**中级** —— 方案要能被验收:验收点必须是**可执行、可观察**的\n` +
    `(跑什么命令、看到什么结果、改了哪些文件),不能是「功能正常」这类判不出真假的话。\n`,
  高级:
    `本次严格度:**高级** —— 除主路径外,方案还要交代可预见的边界与错误路径,\n` +
    `说清主要风险与回滚方式;验收点要覆盖这些,并包含一条「既有测试/构建不回归」。\n`,
  专家:
    `本次严格度:**专家** —— 方案还要指明相关不变量、失败与并发路径的处理方式,\n` +
    `以及契约/类型/文档要跟着改的地方;验收点必须**能证明目标达成**,而不只是「跑绿了」。\n`,
}

/** **执行**环节收到的那一段。 */
const EXEC_SIDE: Record<Strictness, string> = {
  /**
   * 初级这一段被评审改写过两次,原因值得记住。
   *
   * 第一版是「主路径做通即可;边界、测试、重构写进说明即可,不必现在做」。两个真实后果:
   *  1. `executePrompt` 紧接着就渲染 `node.plan` 全文,而 `planPrompt` 逼着 acceptance
   *     写成「跑什么命令、看到什么结果」。于是「测试不必现在做」和验收点里点名的那条
   *     命令**正面打架**,而档位那句在最顶上、方案在它下面。
   *  2. 「写进说明即可」会让执行者往 execStatus 里写「边界 X、并发 Y 未处理」,而这段
   *     文字随后被 acceptPrompt 原样渲染给验收席位 —— 初级档的验收员被告知「验收点里
   *     没写的不要求」,于是**执行者自己承认没做完的东西被盖章为完成**。
   *
   * 修法就是下面这三句:把档位与 plan 的优先级钉死、强制留痕、并直说那条红线。
   */
  初级:
    `本次严格度:**初级** —— 先把主路径做通。\n` +
    `**方案的验收点与重点(keyPoints)里点名要求的事项一件都不能少**;它们之外的边界处理、\n` +
    `额外测试、重构,这一轮可以不做。\n` +
    `不做的每一件,在 execStatus 里单起一行写「本轮未做:…(原因)」——不要写成已完成,也不要不写。\n`,
  中级:
    `本次严格度:**中级** —— 达成验收点,并跑一次与验收点直接相关的命令、把输出写进\n` +
    `execStatus 作为证据。验收点之外的边界与打磨不是这一轮的要求;未做的单起一行写\n` +
    `「本轮未做:…(原因)」,不要写成已完成。\n`,
  高级:
    `本次严格度:**高级** —— 达成验收点,处理可预见的边界与错误路径,并跑既有测试/构建\n` +
    `确认没有引入回归,把命令与结果写进 execStatus。\n`,
  专家:
    `本次严格度:**专家** —— 在高级的基础上,还要守住相关不变量、处理失败与并发路径、\n` +
    `保持契约/类型/文档与实现一致,并给出没有回归的证据。\n`,
}

/**
 * `seatPreamble` 注入的那一段:抬头声明 + 本关特化 + 地板。
 *
 * 返回空串的三种情况,每一种都是刻意的:
 *  - 没设档位 —— 「不设 = 逐字节相同」;
 *  - `observer` —— 见 `STRICTNESS_JUDGING` 的注释(它没有 blocking 字段);
 *  - 其余环节(目前没有)—— 默认不说话,新环节要显式加进来才会收到。
 *
 * 末尾那句「用户点名补充的约束优先于它」是**位置**决定的:调用点把这一段排在定向注入
 * (phaseGuidance / roleGuidance / node.guidance)**之前**,于是它必须自己声明自己是
 * 默认值。少了它,「初级:缺边界一律写 comments」和用户点名的「这里要特别小心并发边界」
 * 会同时在一份提示词里,谁赢由模型掷骰子。
 */
export function strictnessBlock(
  s: Strictness | undefined, phase: PhaseName,
  /**
   * 这一席后面还跟着定向注入吗。
   *
   * 只用来决定要不要说 `YIELD_NOTE` —— 没有任何用户补充时,「用户点名补充的约束优先于它」
   * 说的是一件不存在的事。和 `JUDGE_NOTE` 被 `seatPreamble` 的提前返回挡掉是**同一条
   * 理由**,只是危害小得多(它是条件句,条件不成立就只是空转付钱)。
   */
  hasTargeted = true,
): string {
  if (s === undefined) return ''
  const yieldNote = hasTargeted ? YIELD_NOTE : ''
  if (phase === 'plan') return PLAN_SIDE[s] + yieldNote
  if (phase === 'execute') return EXEC_SIDE[s] + yieldNote
  if (!STRICTNESS_JUDGING.has(phase)) return ''
  const extra = PHASE_EXTRA[phase]?.[s] ?? ''
  // review 判的是方案(那时一行代码都没写),用它自己那份地板 —— 见 REVIEW_FLOOR。
  const floor = phase === 'review' ? REVIEW_FLOOR : FLOOR
  return `本次运行的严格度:**${s}**。\n` + extra + floor + yieldNote
}

const YIELD_NOTE = `(以上是本轮的默认判据;用户点名补充的约束优先于它。)\n`

/**
 * 升/降一档。`d > 0` 收紧,`d < 0` 放松。
 *
 * **「不设」从任一方向都落到专家**,而不是被当成阶梯上的一格。理由:不设档的真实行为是
 * 「全票 + 判据空白」,数值上等于专家(quorum 100),但判据上比任何一档都更不可预测 ——
 * 同一份产出换一个模型就换一个结论。所以从不设出发,唯一诚实的落点是「数字一样、判据
 * 说清楚了」的那一档;之后再按阶梯走。
 */
export function adjustStrictness(cur: Strictness | undefined, d: number): Strictness {
  if (cur === undefined) return '专家'
  const i = STRICTNESS_LEVELS.indexOf(cur)
  const next = Math.min(STRICTNESS_LEVELS.length - 1, Math.max(0, i + (d > 0 ? 1 : -1)))
  return STRICTNESS_LEVELS[next]!
}
