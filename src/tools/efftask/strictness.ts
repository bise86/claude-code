/**
 * `seatPreamble` 注入的那一段:抬头声明 + 本关特化 + 地板。
 *
 * 返回空串的三种情况,每一种都是刻意的:
 *  - 没设档位 —— 「不设 = 逐字节相同」;
 *  - `observer` —— 见 `STRICTNESS_JUDGING` 的注释(它没有 blocking 字段);
 *  - 其余环节(目前没有)—— 默认不说话,新环节要显式加进来才会收到。
 *
 * 末尾那句「用户点名补充的约束优先于它」是**位置**决定的:调用点把这一段排在定向注入
 * (phaseGuidance / roleGuidance / node.guidance)**之前**,于是它必须自己声明自己是
 * 默认值。少了它,「初级:缺边界一律写 comments」和用户点名的「这里要特别小心并发边界」
 * 会同时在一份提示词里,谁赢由模型掷骰子。
 */
export function strictnessBlock(
  s: Strictness | undefined, phase: PhaseName,
  /**
   * 这一席后面还跟着定向注入吗。
   *
   * 只用来决定要不要说 `YIELD_NOTE` —— 没有任何用户补充时,「用户点名补充的约束优先于它」
   * 说的是一件不存在的事。和 `JUDGE_NOTE` 被 `seatPreamble` 的提前返回挡掉是**同一条
   * 理由**,只是危害小得多(它是条件句,条件不成立就只是空转付钱)。
   */
  hasTargeted = true,
): string {
  if (s === undefined) return ''
  const yieldNote = hasTargeted ? YIELD_NOTE : ''
  /**
   * **质疑修复跟着方案侧走,测试修复跟着执行侧走。**
   *
   * 两关都从「裁决」改成了「干活」,而档位对干活的人说的是**做到什么程度**:质疑修复的
   * 产物是一份方案(验收点定到多高就是它的事),测试修复的产物是改过的代码。发裁决侧那
   * 一份的后果是现成的 —— 那一段讲的是「什么该进 blocking」,而它们的输出里没有 blocking:
   * 这个文件顶上记着同一个错误的上一个版本(分析席位收到「写进 execStatus」,而它的
   * schema 里根本没这个字段)。
   */
  if (phase === 'plan' || phase === 'review') return PLAN_SIDE[s] + yieldNote
  if (phase === 'execute' || phase === 'verify') return EXEC_SIDE[s] + yieldNote
  if (!STRICTNESS_JUDGING.has(phase)) return ''
  const extra = PHASE_EXTRA[phase]?.[s] ?? ''
  return `本次运行的严格度:**${s}**。\n` + extra + FLOOR + yieldNote
}

const YIELD_NOTE = `(以上是本轮的默认判据;用户点名补充的约束优先于它。)\n`

/**
 * 升/降一档。`d > 0` 收紧,`d < 0` 放松。
 *
 * **「不设」从任一方向都落到专家**,而不是被当成阶梯上的一格。理由:不设档的真实行为是
 * 「全票 + 判据空白」,数值上等于专家(quorum 100),但判据上比任何一档都更不可预测 ——
 * 同一份产出换一个模型就换一个结论。所以从不设出发,唯一诚实的落点是「数字一样、判据
 * 说清楚了」的那一档;之后再按阶梯走。
 */
export function adjustStrictness(cur: Strictness | undefined, d: number): Strictness {
  if (cur === undefined) return '专家'
  const i = STRICTNESS_LEVELS.indexOf(cur)
  const next = Math.min(STRICTNESS_LEVELS.length - 1, Math.max(0, i + (d > 0 ? 1 : -1)))
  return STRICTNESS_LEVELS[next]!
}
